#!/usr/bin/env bash
# Regenerates packages/shared/src/database.generated.ts from the running local database.
# Run after every migration: pnpm db:migrate && pnpm db:types
set -euo pipefail
cd "$(dirname "$0")/.."
out=packages/shared/src/database.generated.ts
{
  echo "// GENERATED by scripts/gen-types.sh from the local database — do not edit by hand."
  docker compose exec -T meta node -e "
    fetch('http://localhost:8080/generators/typescript?included_schemas=public&postgrest_version=14')
      .then(async (r) => { if (!r.ok) throw new Error(r.status + ' ' + await r.text()); return r.text(); })
      .then((t) => process.stdout.write(t))
      .catch((e) => { console.error(e); process.exit(1); });"
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
